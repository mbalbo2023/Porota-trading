"""R304 pure offhost freeze tests: no SSH, sudo, Docker or deployment."""

from datetime import datetime, timedelta, timezone
from dataclasses import FrozenInstanceError
import hashlib
import json
import unittest
from unittest.mock import patch

from scripts import rc6_host_rootowned_installer_contract as r280
from scripts import rc6_r304_root_install_manifest_freeze as r304


NOW = datetime(2026, 11, 13, 1, 0, tzinfo=timezone.utc)
CANDIDATE = "4fe14abddc4693948c8081840f4ffa60e0f6c8a0"
TREE = "9871d69ff3570dce3ff3203941f7bc615d1ce7d8"


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def source_fixture():
    return {
        "helper": b"#!/usr/bin/python3 -I\n# reviewed candidate helper\n",
        "custody": b"# reviewed candidate custody\n",
        "profiles": b'{"roles":{}}\n',
        "unit_template": b"[Unit]\nDescription=reviewed PAPER unit\n",
    }


def approval_fixture(sources, *, expires_at="2026-11-13T02:00:00Z"):
    return {
        "schema_version": 1, "phase": "GENESIS",
        "candidate_sha": CANDIDATE, "candidate_tree": TREE,
        "artifact_digest": "sha256:" + "c" * 64,
        "image_id": "sha256:" + "d" * 64,
        "daemon_id": "rootful-daemon-rc6", "generation": "e" * 32,
        "run_id": "43301355473", "run_attempt": "1",
        "paper_mode": "PRODUCTION_PAPER", "real_orders_allowed": False,
        "helper_sha256": digest(sources["helper"]),
        "custody_sha256": digest(sources["custody"]),
        "profiles_sha256": digest(sources["profiles"]),
        "unit_template_sha256": digest(sources["unit_template"]),
        "expires_at": expires_at,
    }


def freeze(sources=None, approval=None, source_sha256=None, now=NOW):
    sources = source_fixture() if sources is None else sources
    approval = approval_fixture(sources) if approval is None else approval
    source_sha256 = ({name: digest(raw) for name, raw in sources.items()}
                     if source_sha256 is None else source_sha256)
    return r304.freeze_root_install_manifest(
        candidate_sha=CANDIDATE, candidate_tree=TREE,
        source_bytes=sources, expected_source_sha256=source_sha256,
        approval_intent=approval, now=now)


class R304RootInstallManifestFreezeTest(unittest.TestCase):
    def test_true_five_role_root_manifest_is_deterministic_r280_compatible_and_not_go(self):
        first = freeze()
        second = freeze()
        self.assertEqual(first.manifest_bytes, second.manifest_bytes)
        self.assertEqual(first.approval_bytes, second.approval_bytes)
        self.assertEqual(first.manifest_sha256, digest(first.manifest_bytes))
        self.assertEqual(first.state, "PROPUESTO")
        self.assertIs(first.owner_go_verified, False)
        self.assertIs(first.host_control_verified, False)
        self.assertIs(first.deploy_authorized, False)

        manifest = json.loads(first.manifest_bytes)
        self.assertEqual(set(manifest), {
            "schema", "candidate_sha", "candidate_tree", "paper_mode",
            "real_orders_allowed", "files",
        })
        self.assertEqual(manifest["schema"], "RC6_ROOT_INSTALL_MANIFEST_V1")
        self.assertEqual(manifest["candidate_sha"], CANDIDATE)
        self.assertEqual(manifest["candidate_tree"], TREE)
        self.assertEqual(manifest["paper_mode"], "PRODUCTION_PAPER")
        self.assertIs(manifest["real_orders_allowed"], False)
        self.assertEqual(set(manifest["files"]), {
            "helper", "custody", "profiles", "approval", "unit_template",
        })
        self.assertLessEqual(len(first.manifest_bytes), 8192)
        self.assertEqual(manifest["files"]["approval"], digest(first.approval_bytes))

        # The real R280 pure verifier checks the exact generated bytes;
        # patching its root-only pin is confined to this offline unit test.
        with patch.object(r280, "TRUSTED_MANIFEST_SHA256", first.manifest_sha256):
            verified = r280.verify_approved_bundle(
                first.manifest_bytes, dict(first.files), now=NOW)
        self.assertEqual(verified.manifest_sha256, first.manifest_sha256)
        self.assertIs(verified.host_control_verified, False)

    def test_freeze_cannot_self_approve_or_alias_mutable_source_mapping(self):
        sources = source_fixture()
        result = freeze(sources=sources)
        sources["helper"] = b"changed later"
        self.assertEqual(result.files["helper"], source_fixture()["helper"])
        with self.assertRaises(TypeError):
            result.files["helper"] = b"forged"
        with self.assertRaises(FrozenInstanceError):
            result.state = "HOST_GO"

    def test_mismatch_to_separately_supplied_source_sha_is_rejected(self):
        sources = source_fixture()
        source_sha = {name: digest(raw) for name, raw in sources.items()}
        source_sha["helper"] = "0" * 64
        with self.assertRaises(r304.FreezeHold):
            freeze(sources=sources, source_sha256=source_sha)

    def test_missing_extra_or_malformed_source_hashes_fail_closed(self):
        sources = source_fixture()
        expected = {name: digest(raw) for name, raw in sources.items()}
        for bad in ({"helper": sources["helper"]},
                    {**sources, "unknown": b"unreviewed"}):
            with self.subTest(bad=tuple(sorted(bad))):
                with self.assertRaises(r304.FreezeHold):
                    freeze(sources=bad, approval=approval_fixture(sources),
                           source_sha256=expected)
        for bad in ({"helper": expected["helper"]},
                    {**expected, "unknown": "0" * 64},
                    {**expected, "helper": "not-sha256"}):
            with self.subTest(bad=tuple(sorted(bad))):
                with self.assertRaises(r304.FreezeHold):
                    freeze(source_sha256=bad)

    def test_approval_must_be_full_explicit_intent_not_derived_from_source(self):
        sources = source_fixture()
        approval = approval_fixture(sources)
        cases = [
            {k: v for k, v in approval.items() if k != "run_id"},
            {**approval, "unexpected": "extra"},
            {**approval, "helper_sha256": "0" * 64},
            {**approval, "candidate_tree": "0" * 40},
            {**approval, "image_id": "no-image"},
            {**approval, "phase": "UNKNOWN"},
        ]
        for case in cases:
            with self.subTest(case=case):
                with self.assertRaises(r304.FreezeHold):
                    freeze(sources=sources, approval=case)

    def test_mutated_approval_after_freezing_cannot_validate_different_live_dict(self):
        # Reproduces the reviewer-discovered TOCTOU: a caller changes its
        # mutable mapping after bytes are sealed but before R280 validation.
        sources = source_fixture()
        approval = approval_fixture(sources)
        approval["run_id"] = "INVALID"
        original_canonical = r304._canonical

        def mutate_after_first_snapshot(doc):
            frozen_bytes = original_canonical(doc)
            if doc is approval:
                approval["run_id"] = "43301355473"
            return frozen_bytes

        with patch.object(r304, "_canonical", side_effect=mutate_after_first_snapshot):
            with self.assertRaises(r304.FreezeHold):
                freeze(sources=sources, approval=approval)

    def test_mutated_approval_cannot_reject_valid_frozen_snapshot(self):
        sources = source_fixture()
        approval = approval_fixture(sources)
        original_canonical = r304._canonical

        def invalidate_live_input_after_freeze(doc):
            frozen_bytes = original_canonical(doc)
            if doc is approval:
                approval["run_id"] = "INVALID"
            return frozen_bytes

        with patch.object(r304, "_canonical", side_effect=invalidate_live_input_after_freeze):
            proposed = freeze(sources=sources, approval=approval)
        self.assertEqual(json.loads(proposed.approval_bytes)["run_id"], "43301355473")
        self.assertEqual(proposed.state, "PROPUESTO")

    def test_paper_modes_and_real_order_boolean_fail_closed(self):
        sources = source_fixture()
        approval = approval_fixture(sources)
        for changes in ({"paper_mode": "LIVE"},
                        {"real_orders_allowed": True},
                        {"real_orders_allowed": 0}):
            with self.subTest(changes=changes):
                with self.assertRaises(r304.FreezeHold):
                    freeze(sources=sources, approval={**approval, **changes})

    def test_approval_expiration_and_max_four_hours_are_enforced(self):
        sources = source_fixture()
        for expiry in ("2026-11-13T00:59:59Z", "2026-11-13T01:00:00Z",
                       "2026-11-13T05:00:01Z", "not-a-time"):
            with self.subTest(expiry=expiry):
                with self.assertRaises(r304.FreezeHold):
                    freeze(sources=sources,
                           approval=approval_fixture(sources, expires_at=expiry))
        valid = freeze(sources=sources, approval=approval_fixture(
            sources, expires_at="2026-11-13T05:00:00Z"))
        self.assertEqual(valid.state, "PROPUESTO")

    def test_unrepresentable_four_hour_clock_window_fails_closed(self):
        # R280 computes now+4h; near datetime.max it can raise OverflowError
        # rather than its normal fail-closed InstallHold.
        sources = source_fixture()
        near_max = datetime(9999, 12, 31, 23, 59, 58, tzinfo=timezone.utc)
        with self.assertRaises(r304.FreezeHold):
            freeze(sources=sources, approval=approval_fixture(
                sources, expires_at="9999-12-31T23:59:59Z"), now=near_max)

    def test_untrusted_now_or_bad_helper_fails_before_freeze(self):
        with self.assertRaises(r304.FreezeHold):
            freeze(now=NOW.replace(tzinfo=None))
        sources = source_fixture()
        sources["helper"] = b"#!/usr/bin/env python3\nnot isolated"
        with self.assertRaises(r304.FreezeHold):
            freeze(sources=sources)

    def test_d_release_manifest_101203_bytes_and_wrong_schema_are_not_root_manifest(self):
        # Actual D log: porota-deploy-bundle-v2-manifest.json is 101203 B.
        d_manifest_shape = (b'{"schema_version":1,"status":"GREEN"}' +
                            b" " * (101203 - len(b'{"schema_version":1,"status":"GREEN"}')))
        self.assertEqual(len(d_manifest_shape), 101203)
        with self.assertRaises(r304.FreezeHold):
            r304.validate_root_manifest_bytes(d_manifest_shape)
        with self.assertRaises(r304.FreezeHold):
            r304.validate_root_manifest_bytes(b'{"schema_version":1,"status":"GREEN"}')

    def test_root_manifest_parser_rejects_duplicate_keys_nan_and_missing_role(self):
        valid = freeze().manifest_bytes
        for bad in (
            b'{"schema":"RC6_ROOT_INSTALL_MANIFEST_V1","schema":"OTHER"}',
            b'{"schema":"RC6_ROOT_INSTALL_MANIFEST_V1","x":NaN}',
            valid.replace(b'"unit_template":', b'"unit_missing":', 1),
        ):
            with self.subTest(bad=bad[:60]):
                with self.assertRaises(r304.FreezeHold):
                    r304.validate_root_manifest_bytes(bad)


if __name__ == "__main__":
    unittest.main()
