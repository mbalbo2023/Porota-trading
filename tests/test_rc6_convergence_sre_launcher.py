def prepare_launcher(tmp_path, monkeypatch, inputs):
    monkeypatch.setattr(manager, "ROOT", tmp_path)
    monkeypatch.setattr(manager, "DATA", tmp_path / "data")
    monkeypatch.setattr(manager, "env_file", lambda: inputs)
    directory = tmp_path / "data/diagnosticos"; directory.mkdir(parents=True, exist_ok=True)
    (directory / "dashboard_preview_v1633.env").write_text(
        "DASHBOARD_ACCESS_TOKEN=OFFLINE_FIXTURE\nPOROTA_DYNAMIC_CAPACITY_MODE=APPROVED\n"
        "POROTA_SHADOW_RUNTIME_ROOT=/wrong/preview-root\nPOROTA_BUILD_SHA=spoofed\n")


def read_env(path):
    return dict(line.split("=", 1) for line in path.read_text().splitlines() if "=" in line)


@pytest.fixture
def disk_path(monkeypatch):
    # /tmp may be tmpfs even when its size exceeds the runtime's 32 MiB. Use
    # the repository's actual disk mount, with an isolated disposable layout.
    # The production constants remain 1000. GitHub's host runner can be 1001;
    # the synthetic native layout uses its actual owner for O_NOATIME.
    monkeypatch.setattr(manager, "SQLITE_SCRATCH_UID", os.geteuid())
    monkeypatch.setattr(manager, "SQLITE_SCRATCH_GID", os.getegid())
    with tempfile.TemporaryDirectory(prefix="rc6-native-disk-",
                                     dir=Path(__file__).resolve().parents[2]) as directory:
        yield Path(directory)


@pytest.mark.parametrize("mode,status", [("OFF", "OFF_BASELINE"), ("SHADOW", "SHADOW_BASELINE"), ("APPROVED", "APPROVED_DYNAMIC")])
def test_six_inputs_flow_through_canonical_env_into_real_capacity_controller(tmp_path, monkeypatch, wire, mode, status):
    policy, recommendation, report, approval, at = approved(wire)
    policy["mode"] = mode
    inputs = {"POROTA_DYNAMIC_CAPACITY_MODE": mode,
              "POROTA_CAPACITY_SHADOW_PATH": str(artifact_root(CONTAINER_DB) / "dynamic-shadow/CURRENT.json")}
    for key, value in (("POLICY", policy), ("REPORT", report), ("RECOMMENDATION", recommendation), ("APPROVAL", approval)):
        name = f"/app/data/rc6-capacity/{key.lower()}.json"
        inputs["POROTA_CAPACITY_" + key + "_PATH"] = name
        host = tmp_path / name.removeprefix("/app/"); host.parent.mkdir(parents=True, exist_ok=True)
        host.write_text(json.dumps(value))
    prepare_launcher(tmp_path, monkeypatch, inputs)
    observer = manager.observer_runtime_env(); dashboard = manager.dashboard_env("PRODUCTION_PAPER")
    observer_values, dashboard_values = read_env(observer), read_env(dashboard)
    for key in manager.CAPACITY_ENV_KEYS:
        assert observer_values[key] == dashboard_values[key] == inputs[key]
    canonical_root = str(artifact_root(CONTAINER_DB) / "dynamic-shadow")
    assert observer_values["POROTA_DYNAMIC_SHADOW_ROOT"] == dashboard_values["POROTA_SHADOW_RUNTIME_ROOT"] == canonical_root
    assert stat.S_IMODE(observer.stat().st_mode) == stat.S_IMODE(dashboard.stat().st_mode) == 0o600
    # This mapping is the isolated fixture's /app mount. Controller reads the
    # real files produced above, using the exact env generated by the launcher.
    mounted_env = dict(observer_values)
    for key in manager.CAPACITY_ENV_KEYS[1:]:
        if mounted_env[key]: mounted_env[key] = str(tmp_path / mounted_env[key].removeprefix("/app/"))
    resolved = RuntimeCapacityController(environ=mounted_env).state(at)
    assert resolved["status"] == status
    assert resolved["real_orders_sent"] == 0


