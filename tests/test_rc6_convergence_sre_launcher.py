def source_fixture(tmp_path, monkeypatch):
    monkeypatch.setattr(manager, "ROOT", tmp_path)
    for relative in manager.DASHBOARD_RUNTIME_SOURCES:
        path = tmp_path / relative
        if relative == "rc6_trader_dashboard": path = path / "__init__.py"
        path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(b"# immutable source fixture\n")
    (tmp_path / "rc6_trader_dashboard/projection.py").write_bytes(b"# immutable projection fixture\n")
    policy_root = tmp_path / "ops/policy"; policy_root.mkdir(parents=True)
    (policy_root / "rc6-dynamic-capacity-v1.json").write_bytes(b'{"mode":"OFF"}\n')
    for args in (("init", "-q"), ("config", "user.name", "Offline fixture"), ("config", "user.email", "fixture@example.invalid"),
                 ("add", "."), ("commit", "-qm", "exact dashboard mount source")):
        subprocess.run(["git", "-C", str(tmp_path), *args], check=True, capture_output=True)
    manifest = create_source_manifest(tmp_path); raw = canonical_bytes(manifest)
    (tmp_path / "POROTA_SOURCE_PROVENANCE.json").write_bytes(raw)
    labels = {"porota.commit": manifest["candidate_sha"], "porota.tree": manifest["candidate_tree_sha"],
              "porota.source-manifest-sha256": hashlib.sha256(raw).hexdigest(), "porota.predeploy": "v2"}
    calls = []
    def run(*args, **kwargs):
        calls.append(args)
        return SimpleNamespace(stdout=json.dumps(labels))
    monkeypatch.setattr(manager, "run", run)
    return manifest, labels, calls


def test_package_and_hook_match_same_image_source_before_container_mutation(tmp_path, monkeypatch):
    manifest, labels, calls = source_fixture(tmp_path, monkeypatch)
    identity = manager.verify_dashboard_source_identity(manager.DASHBOARD_RUNTIME_SOURCES)
    assert identity["candidate_sha"] == manifest["candidate_sha"]
    assert manager._runtime_build_identity()["POROTA_CANDIDATE_TREE_SHA"] == manifest["candidate_tree_sha"]
    assert all(call[:3] == ("docker", "image", "inspect") for call in calls)
    (tmp_path / "rc6_trader_dashboard/__init__.py").write_bytes(b"# stale package\n")
    with pytest.raises(RuntimeError, match="PROVENANCE_MISMATCH"):
        manager.verify_dashboard_source_identity(manager.DASHBOARD_RUNTIME_SOURCES)
    assert not any("rm" in call for call in calls)


