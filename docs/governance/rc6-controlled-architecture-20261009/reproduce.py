def eligible_roots():
    sys.path.insert(0, str(ROOT))
    from scripts.porota_artifact_provenance import dockerignore_exclusion, is_bundle_path
    ignore = (ROOT / ".dockerignore").read_text()
    paths = git("ls-tree", "-r", "--name-only", CODE).decode().splitlines()
    rows = []
    for path in paths:
        if not path.startswith(("notes/", "rc6_audit_evidence/")):
            continue
        raw = (ROOT / path).read_bytes()
        role = ("SOFTWARE_HELPER_KEEP" if path.startswith("rc6_audit_evidence/") and path.split("/")[-1] in HELPERS
                else "TEST_PROBE_SOURCE_KEEP_IN_SOURCE" if path.endswith(".py")
                else "RCA_KEEP_IN_GIT_NOT_BUNDLE" if path.endswith(".md") else "GENERATED_EVIDENCE_PRESERVE")
        rows.append({"path": path, "bytes": len(raw), "sha256": sha(raw), "role": role,
            "native_bundle_eligible": is_bundle_path(path), "native_context_eligible": dockerignore_exclusion(path, ignore) is None,
            "proposed_deploy_exclusion": proposed_exclusion(path), "unique_evidence": "NO_VERIFICADO_PRESERVE",
            "custody": "GIT_AT_"+CODE})
    assert len(rows) == 36 and sum(r["bytes"] for r in rows) == 6658367
    assert all(r["native_bundle_eligible"] and r["native_context_eligible"] for r in rows)
    assert sum(not r["proposed_deploy_exclusion"] for r in rows) == 6
    assert sum(r["bytes"] for r in rows if not r["proposed_deploy_exclusion"]) == 116679
    return rows


def hash_original_blobs(destination):
    rows = list(csv.DictReader((PREVIOUS / "pr476-complete-inventory.csv").open()))
    ids = Counter(r["head_blob_sha1"] for r in rows if r["head_blob_sha1"])
    expected = {r["head_blob_sha1"]: int(r["head_logical_bytes"]) for r in rows if r["head_blob_sha1"]}
    # Verify membership in the original PR476 tree; a hash-shaped string is
    # insufficient. Do not use modified WIP bytes for the old path inventory.
    tree = {}
    for item in git("ls-tree", "-r", "-z", PR476).split(b"\0"):
        if item:
            metadata, path = item.split(b"\t", 1); tree[path.decode()] = metadata.split()[2].decode()
    assert len(rows) == 3127 and all(tree.get(r["path"]) == r["head_blob_sha1"] for r in rows if r["head_blob_sha1"])
    with tempfile.TemporaryFile() as queue, destination.open("w", newline="") as target:
        queue.write("".join(oid+"\n" for oid in sorted(ids)).encode()); queue.seek(0)
        process = subprocess.Popen(["git", "--no-replace-objects", "-C", str(ROOT), "cat-file", "--batch"],
            stdin=queue, stdout=subprocess.PIPE)
        writer = csv.writer(target, lineterminator="\n"); writer.writerow(["git_blob_sha1", "bytes", "sha256", "path_copies_in_previous_inventory"])
        for oid in sorted(ids):
            header = process.stdout.readline().decode().strip().split()
            assert len(header) == 3 and header[:2] == [oid, "blob"] and int(header[2]) == expected[oid]
            size = int(header[2]); digest = hashlib.sha256(); git_digest = hashlib.sha1(b"blob "+str(size).encode()+b"\0")
            remaining = size
            while remaining:
                raw = process.stdout.read(min(1024**2, remaining)); assert raw
                remaining -= len(raw); digest.update(raw); git_digest.update(raw)
            assert process.stdout.read(1) == b"\n" and git_digest.hexdigest() == oid
            writer.writerow([oid, size, digest.hexdigest(), ids[oid]])
        assert process.stdout.read() == b"" and process.wait() == 0
    return {"paths": len(rows), "unique_head_blobs": len(ids), "sha256_join_index": destination.name,
        "join_to": "../rc6-systemic-review-20261008/pr476-complete-inventory.csv",
        "original_tree_membership_and_blob_sha1_verified": True, "sha256": sha(destination.read_bytes())}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--hash-pr476", action="store_true")
    parser.add_argument("--check-prospective-base")
    args = parser.parse_args(); output = args.output_dir.resolve(); output.mkdir(parents=True, exist_ok=True)
    result, schedule = calculate(); roots = eligible_roots()
    result["eligible_evidence_roots"] = {"files": len(roots), "bytes": sum(r["bytes"] for r in roots),
        "keep_software_files": 6, "keep_software_bytes": 116679, "proposed_excluded_files": 30,
        "proposed_excluded_bytes": 6541688, "actual_image_inspected": False}
    with (output / "horizon-schedule.csv").open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(schedule[0]), lineterminator="\n");writer.writeheader();writer.writerows(schedule)
    (output / "evidence-roots.json").write_text(json.dumps(roots, indent=2, sort_keys=True)+"\n")
    if args.hash_pr476:
        result["pr476_sha256_custody_index"] = hash_original_blobs(output / "pr476-blob-sha256.csv")
    if args.check_prospective_base:
        paths = git("diff", "--name-only", "--diff-filter=AM", args.check_prospective_base, "HEAD").decode().splitlines()
        result["prospective_evidence_guard"] = evidence_guard(paths)
    (output / "analysis.json").write_text(json.dumps(result, indent=2, sort_keys=True)+"\n")
    print(json.dumps({"analysis": "PASS_ARITHMETIC_AND_STATIC_ONLY", "G0": result["g0"]["status"],
        "G5": result["g5"]["status"], "qualification": False, "outputs": sorted(p.name for p in output.iterdir())}, sort_keys=True))


if __name__ == "__main__":
    main()
