def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def document(path):
    return json.loads(path.read_bytes())


def git(*args):
    return subprocess.check_output(["git", "--no-replace-objects", "-C", str(ROOT), *args],
        env={**__import__("os").environ, "GIT_NO_LAZY_FETCH": "1", "GIT_OPTIONAL_LOCKS": "0"})


def proposed_exclusion(path):
    return any(path.startswith(prefix) for prefix in GENERATED_ROOTS) or path == DEPLOY_EXCLUSIONS_PROPOSED[-1]


def evidence_guard(paths):
    """Prospective role rule only; it is NOT a G0--G8 qualification gate.

    These two roots are declared generated evidence/probe custody roles, not
    runtime code. Existing baseline blobs are grandfathered and never deleted.
    Genuine fixtures belong in tests/fixtures with their provenance preserved.
    New generated bytes require an external verified destination, not a commit
    to these bulk roots. Index updates belong in concise governance indices.
    """
    return {"status": "BLOCK_EVIDENCE_POLICY" if any(proposed_exclusion(p) for p in paths) else "PASS",
        "paths_requiring_custody_instead_of_new_git_payload": sorted(p for p in paths if proposed_exclusion(p)),
        "is_material_gate": False, "deletion_authorized": False, "installed_in_CI": False}


